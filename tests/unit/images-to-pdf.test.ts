async function pageCount(bytes: Uint8Array): Promise<number> {
  return (await PDFDocument.load(bytes)).getPageCount();
}

describe('imagesToPdf', () => {
  it('produces a PDF with one page per image', async () => {
    const out = await imagesToPdf([PNG_1x1, PNG_1x1, JPG_1x1]);
    expect(await pageCount(out)).toBe(3);
  });

  it('accepts File inputs with PNG/JPG mime types', async () => {
    const png = new File([PNG_1x1], 'a.png', { type: 'image/png' });
    const jpg = new File([JPG_1x1], 'b.jpg', { type: 'image/jpeg' });
    const out = await imagesToPdf([png, jpg]);
    expect(await pageCount(out)).toBe(2);
  });

  it('preserves the order of images', async () => {
    const out = await imagesToPdf([PNG_1x1, JPG_1x1]);
    expect(await pageCount(out)).toBe(2);
  });

  it('returns a valid PDF (starts with %PDF)', async () => {
    const out = await imagesToPdf([PNG_1x1]);
    const header = String.fromCharCode(...out.slice(0, 4));
    expect(header).toBe('%PDF');
  });

  it('throws on empty list', async () => {
    await expect(imagesToPdf([])).rejects.toThrow(/at least one/i);
  });

  it('throws on unsupported mime', async () => {
    const txt = new File([new Uint8Array([0])], 'a.txt', { type: 'text/plain' });
    await expect(imagesToPdf([txt])).rejects.toThrow(/png|jpeg|unsupported/i);
  });
});
