async function makePdf(pageCount: number): Promise<Uint8Array> {
  const doc = await PDFDocument.create();
  for (let i = 0; i < pageCount; i++) doc.addPage([400, 600]);
  return doc.save();
}

async function pageCount(bytes: Uint8Array): Promise<number> {
  return (await PDFDocument.load(bytes)).getPageCount();
}

describe('watermarkPdf', () => {
  let threePage: Uint8Array;

  beforeAll(async () => {
    threePage = await makePdf(3);
  });

  it('applies a text watermark to every page (page count preserved, output larger)', async () => {
    const out = await watermarkPdf(threePage, {
      kind: 'text',
      text: 'CONFIDENTIAL',
      opacity: 0.3,
      fontSize: 80,
      angle: -45,
    });
    expect(await pageCount(out)).toBe(3);
    expect(out.byteLength).toBeGreaterThan(threePage.byteLength);
    const header = String.fromCharCode(...out.slice(0, 4));
    expect(header).toBe('%PDF');
  });

  it('applies an image watermark from a PNG Uint8Array', async () => {
    const out = await watermarkPdf(threePage, {
      kind: 'image',
      image: PNG_1x1,
      opacity: 0.3,
      scale: 0.4,
      angle: -45,
    });
    expect(await pageCount(out)).toBe(3);
    expect(out.byteLength).toBeGreaterThan(threePage.byteLength);
  });

  it('applies an image watermark from a JPEG File', async () => {
    const file = new File([JPG_1x1 as BlobPart], 'logo.jpg', { type: 'image/jpeg' });
    const out = await watermarkPdf(threePage, {
      kind: 'image',
      image: file,
      opacity: 0.3,
      scale: 0.4,
      angle: -45,
    });
    expect(await pageCount(out)).toBe(3);
  });

  it('throws when text is empty or whitespace-only', async () => {
    await expect(
      watermarkPdf(threePage, { kind: 'text', text: '   ', opacity: 0.3, fontSize: 80, angle: -45 }),
    ).rejects.toThrow(/empty/i);
  });

  it('throws on unsupported image format', async () => {
    const bogus = new Uint8Array([0x00, 0x01, 0x02, 0x03]);
    await expect(
      watermarkPdf(threePage, { kind: 'image', image: bogus, opacity: 0.3, scale: 0.4, angle: -45 }),
    ).rejects.toThrow(/png|jpeg|unsupported/i);
  });

  it('throws on non-Latin characters (Helvetica is WinAnsi only)', async () => {
    await expect(
      watermarkPdf(threePage, {
        kind: 'text',
        text: '日本語',
        opacity: 0.3,
        fontSize: 80,
        angle: -45,
      }),
    ).rejects.toThrow(/unsupported character|latin/i);
  });

  it('throws on empty PDF input', async () => {
    await expect(
      watermarkPdf(new Uint8Array(0), {
        kind: 'text',
        text: 'TOP SECRET',
        opacity: 0.3,
        fontSize: 80,
        angle: -45,
      }),
    ).rejects.toThrow();
  });

  it('accepts a File input (text mode)', async () => {
    const f = new File([threePage as BlobPart], 'doc.pdf', { type: 'application/pdf' });
    const out = await watermarkPdf(f, {
      kind: 'text',
      text: 'DRAFT',
      opacity: 0.5,
      fontSize: 60,
      angle: 0,
    });
    expect(await pageCount(out)).toBe(3);
  });
});
